def build_demo_cases(document_id: int, chunk_ids: list[int], fingerprint: str) -> list[dict]:
    cases = []
    for index, (category, question, points, behavior) in enumerate(DEFAULT_CASES):
        history = []
        for user, assistant in FOLLOWUP_HISTORY.get(index, []):
            history.extend([{'role': 'user', 'content': user}, {'role': 'assistant', 'content': assistant}])
        cases.append({
            'id': f'air-{index + 1:02}', 'category': category, 'question': question,
            'history': history, 'required_points': points, 'expected_behavior': behavior,
            'expected_chunk_ids': chunk_ids if behavior == 'answered' else [],
            'reference_document_id': document_id, 'reference_fingerprint': fingerprint,
            'forbidden': ['编造产品参数', '声称已经执行退款或维修', '索取用户密码或验证码'],
        })
    return cases

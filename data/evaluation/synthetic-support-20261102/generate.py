FIELDS = 'import_key title description customer_name customer_email product module category priority status solution'.split()
scenarios = []
for i, line in enumerate(CASES.splitlines(), 1):
    module, category, priority, symptom, evidence, cause, steps = line.split('|')
    scenarios.append(dict(scenario_id=f'S{i:03}', module=module, category=category, priority=priority,
                          symptom=symptom, evidence=evidence, cause=cause, steps=steps))
assert len(scenarios) == 50
rows, labels, questions, answers = [], [], [], []
for s in scenarios:
    relevant = []
    for j in range(40):
        n = len(rows) + 1
        key = f'sim20261102-{n:04}'
        relevant.append(key)
        channel = ['网页在线咨询', '电话转录', '邮件反馈', '客服回访'][j % 4]
        description = (f'【合成演示，非真实客户】模拟组织{j+1:02}通过{channel}反馈：{s["symptom"]}。'
                       f'受影响账号{j % 5 + 1}个。诊断记录：{s["evidence"]}。')
        solution = f'模拟核实原因：{s["cause"]}。处理步骤：{s["steps"]}。结案条件：按上述复测标准确认原问题消失；本记录仅为模拟已解决案例。'
        rows.append(dict(zip(FIELDS, [key, f'模拟：{s["symptom"]}（{n:04}）', description,
                       f'模拟客户{n:04}', f'sim{n:04}@example.com', '演示协作平台', s['module'],
                       s['category'], s['priority'], 'resolved', solution], strict=True)))
        labels.append(dict(import_key=key, scenario_id=s['scenario_id'], root_cause=s['cause'], evidence=s['evidence']))
    for kind in ['diagnose', 'clarify']:
        qid = f'Q{len(questions)+1:03}'
        question = (f'我们遇到{s["symptom"]}。排查时发现：{s["evidence"]}。请说明可能原因和下一步怎么处理。'
                    if kind == 'diagnose' else f'你好，{s["symptom"]}，能帮我看看吗？')
        questions.append(dict(id=qid, type=kind, question=question))
        answers.append(dict(id=qid, scenario_id=s['scenario_id'], type=kind,
                            expected_cause=s['cause'] if kind == 'diagnose' else '信息不足，不得直接定因',
                            expected_evidence=s['evidence'],
                            expected_steps=s['steps'] if kind == 'diagnose' else '先追问具体错误提示、发生时间、影响范围、最近变更和已尝试步骤，再根据证据排查',
                            forbidden=['索取密码或验证码', '无证据承诺已经修复或退款', '把可能原因说成已核实原因'],
                            relevant_import_keys=relevant if kind == 'diagnose' else []))

with (ROOT / '工单2000条.csv').open('w', encoding='utf-8-sig', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=FIELDS)
    writer.writeheader()
    writer.writerows(rows)
for name, values in [('工单原因标注.jsonl', labels), ('测试问题100题.jsonl', questions), ('测试参考答案.jsonl', answers)]:
    (ROOT / name).write_text(''.join(json.dumps(v, ensure_ascii=False)+'\n' for v in values), encoding='utf-8')
